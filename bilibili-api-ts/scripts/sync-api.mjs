import { existsSync } from "node:fs";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, "..");
const vendorDir = path.join(projectRoot, "vendor", "api");

function resolvePythonApiDir() {
    const explicit = process.env.BILIBILI_API_PYTHON_DIR;
    if (explicit) {
        const direct = path.join(explicit, "bilibili_api", "data", "api");
        return existsSync(direct) ? direct : path.join(explicit, "data", "api");
    }
    let current = projectRoot;
    for (let depth = 0; depth < 6; depth += 1) {
        current = path.dirname(current);
        const candidate = path.join(current, "bilibili-api-python", "bilibili_api", "data", "api");
        if (existsSync(candidate)) return candidate;
    }
    return null;
}

const pythonApiDir = resolvePythonApiDir();
const sourceDir = pythonApiDir || vendorDir;
const outputDir = path.join(projectRoot, "src", "data", "api");

/**
 * article-category -> articleCategoryData
 * interactive_video -> interactiveVideoData
 */
function toExportName(fileName) {
    const baseName = fileName.replace(/\.json$/, "");
    const camelCase = baseName
        .split(/[-_]/)
        .filter(Boolean)
        .map((part, index) =>
            index === 0
                ? part
                : part.charAt(0).toUpperCase() + part.slice(1),
        )
        .join("");

    return `${camelCase}Data`;
}

function toModulePath(fileName) {
    return `./${fileName.replace(/\.json$/, "")}`;
}

async function main() {
    const entries = await readdir(sourceDir);
    const jsonFiles = entries
        .filter((entry) => entry.endsWith(".json"))
        .sort();

    if (jsonFiles.length === 0) {
        throw new Error(`No JSON files found in ${sourceDir}`);
    }

    await mkdir(outputDir, { recursive: true });
    if (sourceDir === pythonApiDir) await mkdir(vendorDir, { recursive: true });

    const generated = [];
    const exportNames = new Map();

    for (const fileName of jsonFiles) {
        const key = fileName.replace(/\.json$/, "");
        const exportName = toExportName(fileName);

        if (exportNames.has(exportName)) {
            throw new Error(
                `Export name conflict: "${exportName}" generated by both "${exportNames.get(exportName)}" and "${fileName}"`,
            );
        }
        exportNames.set(exportName, fileName);

        const raw = await readFile(path.join(sourceDir, fileName), "utf8");
        if (sourceDir === pythonApiDir) {
            await writeFile(path.join(vendorDir, fileName), raw, "utf8");
        }
        const value = JSON.parse(raw);
        const body = JSON.stringify(value, null, 2);

        const content = `export const ${exportName} = ${body} as const;\n`;
        await writeFile(path.join(outputDir, `${key}.ts`), content, "utf8");

        generated.push({ key, exportName });
    }

    const imports = generated
        .map(({ key, exportName }) => {
            return `import { ${exportName} } from "${toModulePath(key)}";`;
        })
        .join("\n");

    const entriesCode = generated
        .map(({ key, exportName }) => {
            return `    ${JSON.stringify(key)}: ${exportName},`;
        })
        .join("\n");

    const indexContent = `${imports}\n\nexport const apiData: Record<string, unknown> = {\n${entriesCode}\n};\n`;
    await writeFile(path.join(outputDir, "index.ts"), indexContent, "utf8");

    console.log(`Generated ${generated.length} data modules in ${outputDir}`);
    console.log(`Source: ${sourceDir}`);
    for (const { key, exportName } of generated) {
        console.log(`  ${key}.json -> ${exportName}`);
    }
}

main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
